<?php
declare(strict_types=1);

namespace Pml\Benchmarks\Report;

use Pml\Benchmarks\System\SystemInfo;

/**
 * Generates a markdown benchmark report from PHPBench JSON output
 * and (optionally) Python comparison JSON files.
 *
 * Usage:
 *   vendor/bin/phpbench run benchmarks/ --report=aggregate \
 *       --output=json --output-path=benchmarks/results/pml_latest.json
 *
 *   php benchmarks/pytorch/benchmark_numpy.py --json > benchmarks/results/numpy_latest.json
 *   php benchmarks/pytorch/benchmark_pytorch.py --json > benchmarks/results/torch_latest.json
 *
 *   php benchmarks/Report/ReportGenerator.php \
 *       --pml=benchmarks/results/pml_latest.json \
 *       --numpy=benchmarks/results/numpy_latest.json \
 *       --torch=benchmarks/results/torch_latest.json \
 *       --output=benchmarks/results/report_latest.md
 */
final class ReportGenerator
{
    private SystemInfo $sysInfo;
    private array $pmlResults   = [];
    private array $numpyResults = [];
    private array $torchResults = [];
    private array $sklearnResults = [];

    public function __construct()
    {
        $this->sysInfo = SystemInfo::collect();
    }

    public function loadPml(string $jsonPath): self
    {
        $data = $this->loadJson($jsonPath);
        // PHPBench aggregate JSON: { "suites": [{"subjects": [{...}] }] }
        if (isset($data['suites'])) {
            foreach ($data['suites'] as $suite) {
                foreach ($suite['benchmarks'] ?? [] as $benchmark) {
                    foreach ($benchmark['subjects'] ?? [] as $subject) {
                        $key = $benchmark['class'] . '::' . $subject['name'];
                        $stats = $subject['iterations'][0]['stats'] ?? [];
                        $this->pmlResults[$key] = [
                            'time_mode_us' => ($stats['mode'] ?? 0) / 1000,  // ns→µs
                            'time_mean_us' => ($stats['mean'] ?? 0) / 1000,
                            'rstdev'       => $stats['rstdev'] ?? 0,
                            'mem_peak_mb'  => ($stats['mem_peak'] ?? 0) / 1048576,
                            'revs'         => $subject['iterations'][0]['revs'] ?? 0,
                        ];
                    }
                }
            }
        }
        return $this;
    }

    public function loadNumpy(string $jsonPath): self
    {
        $this->numpyResults = $this->loadJson($jsonPath)['benchmarks'] ?? [];
        return $this;
    }

    public function loadTorch(string $jsonPath): self
    {
        $this->torchResults = $this->loadJson($jsonPath)['benchmarks'] ?? [];
        return $this;
    }

    public function loadSklearn(string $jsonPath): self
    {
        $this->sklearnResults = $this->loadJson($jsonPath)['benchmarks'] ?? [];
        return $this;
    }

    public function generate(): string
    {
        $report = [];

        $report[] = '# PML Benchmark Report';
        $report[] = '';
        $report[] = '> Auto-generated by `benchmarks/Report/ReportGenerator.php`';
        $report[] = '> Do not edit manually.';
        $report[] = '';
        $report[] = '## System Specification';
        $report[] = '';
        $report[] = '```';
        foreach ($this->sysInfo->toArray() as $k => $v) {
            if (is_array($v)) {
                $v = implode(' ', array_slice(
                    array_filter($v, fn($f) => in_array($f, ['avx2', 'avx512f', 'fma', 'sse4_2'])), 0, 6
                ));
            }
            $report[] = sprintf('%-22s %s', $k . ':', $v);
        }
        $report[] = '```';
        $report[] = '';

        $report[] = '## PML Results';
        $report[] = '';

        if (empty($this->pmlResults)) {
            $report[] = '*No PHPBench results loaded. Run:*';
            $report[] = '```bash';
            $report[] = 'vendor/bin/phpbench run benchmarks/ --report=aggregate \\';
            $report[] = '    --output=json --output-path=benchmarks/results/pml_latest.json';
            $report[] = '```';
        } else {
            $report[] = '| Benchmark | Time (µs, mode) | rstdev | Mem Peak (PHP) |';
            $report[] = '|---|---|---|---|';
            foreach ($this->pmlResults as $key => $r) {
                $short = substr($key, strrpos($key, '\\') + 1);
                $report[] = sprintf(
                    '| %s | %.1f | %.1f%% | %.2f MB |',
                    $short,
                    $r['time_mode_us'],
                    $r['rstdev'],
                    $r['mem_peak_mb'],
                );
            }
        }

        $report[] = '';
        $report[] = '## Comparison: PML vs NumPy vs PyTorch CPU';
        $report[] = '';

        if (!empty($this->numpyResults) || !empty($this->torchResults)) {
            $report[] = $this->renderComparisonTable();
        } else {
            $report[] = '*No comparison results loaded.*';
            $report[] = '*Run `scripts/bench.sh --compare` to generate them.*';
        }

        $report[] = '';
        $report[] = '## Notes';
        $report[] = '';
        $report[] = '- All times in this report are median (mode) over measured iterations.';
        $report[] = '- PHP `mem_peak` does not include C tensor allocations.';
        $report[] = '- For RSS-based memory comparison, use `scripts/bench.sh --memory`.';
        $report[] = '- `rstdev` > 5% indicates noisy measurement — re-run with lower system load.';
        $report[] = '';
        $report[] = '---';
        $report[] = sprintf('*Generated: %s*', date('Y-m-d H:i:s T'));

        return implode("\n", $report);
    }

    public function save(string $path): void
    {
        $report = $this->generate();
        $dir    = dirname($path);
        if (!is_dir($dir)) {
            mkdir($dir, 0755, true);
        }
        file_put_contents($path, $report);
        echo "Report saved to: {$path}\n";
    }

    public function saveSystemSpec(string $path): void
    {
        file_put_contents($path, $this->sysInfo->toJson());
        echo "System spec saved to: {$path}\n";
    }

    // ─── Private ────────────────────────────────────────────────────────────

    private function renderComparisonTable(): string
    {
        $operations = [
            'matmul_1kx1k'   => 'GEMM 1024×1024',
            'sigmoid_1M'     => 'Sigmoid 1M elem',
            'relu_1M'        => 'ReLU 1M elem',
            'add_1M'         => 'Add 1M elem',
            'mlp_forward'    => 'MLP forward (10K samples)',
            'softmax_10kx10' => 'Softmax 10K×10',
        ];

        $lines = ['| Operation | PML | NumPy | PyTorch CPU | PML vs NumPy |'];
        $lines[] = '|---|---|---|---|---|';

        foreach ($operations as $key => $label) {
            $pml   = $this->pmlTimeMs($key);
            $np    = $this->numpyTimeMs($key);
            $torch = $this->torchTimeMs($key);
            $ratio = ($pml > 0 && $np > 0) ? round($np / $pml, 2) : null;

            $lines[] = sprintf(
                '| %s | %s | %s | %s | %s |',
                $label,
                $pml   > 0 ? "{$pml} ms"   : 'N/A',
                $np    > 0 ? "{$np} ms"    : 'N/A',
                $torch > 0 ? "{$torch} ms" : 'N/A',
                $ratio !== null ? ($ratio >= 1 ? "{$ratio}× faster" : round(1/$ratio, 2) . "× slower") : 'N/A',
            );
        }

        return implode("\n", $lines);
    }

    private function pmlTimeMs(string $key): float
    {
        foreach ($this->pmlResults as $benchKey => $r) {
            if (str_contains(strtolower($benchKey), strtolower($key))) {
                return round($r['time_mode_us'] / 1000, 2);
            }
        }
        return 0.0;
    }

    private function numpyTimeMs(string $key): float
    {
        return round(($this->numpyResults[$key]['time_sec'] ?? 0) * 1000, 2);
    }

    private function torchTimeMs(string $key): float
    {
        return round(($this->torchResults[$key]['time_sec'] ?? 0) * 1000, 2);
    }

    private function loadJson(string $path): array
    {
        if (!is_readable($path)) {
            throw new \RuntimeException("Cannot read benchmark results: {$path}");
        }
        $data = json_decode(file_get_contents($path), true);
        if ($data === null) {
            throw new \RuntimeException("Invalid JSON in: {$path}");
        }
        return $data;
    }
}

// CLI entry point
if (PHP_SAPI === 'cli' && basename(__FILE__) === basename($_SERVER['PHP_SELF'] ?? '')) {
    require_once dirname(__DIR__, 2) . '/vendor/autoload.php';

    $opts = getopt('', ['pml:', 'numpy:', 'torch:', 'sklearn:', 'output:', 'sysinfo']);

    $gen = new ReportGenerator();

    if (isset($opts['sysinfo'])) {
        SystemInfo::collect()->print();
        exit(0);
    }

    if (isset($opts['pml']))     $gen->loadPml($opts['pml']);
    if (isset($opts['numpy']))   $gen->loadNumpy($opts['numpy']);
    if (isset($opts['torch']))   $gen->loadTorch($opts['torch']);
    if (isset($opts['sklearn'])) $gen->loadSklearn($opts['sklearn']);

    $output = $opts['output'] ?? ('benchmarks/results/report_' . date('Y-m-d_His') . '.md');
    $gen->save($output);
}
